// Helper: search both languages + alt translations
export function searchVocab(query: string): BilingualWord[] {
  const q = query.trim().toLowerCase();
  if (!q) return VOCAB_BANK;
  return VOCAB_BANK.filter(w => {
    const haystack = [
      w.en, w.uz, ...(w.uzAlt ?? []),
      w.defEn, w.defUz, w.phonetic, w.category, w.level,
    ].join(' ').toLowerCase();
    return haystack.includes(q);
  });
}
